// chdirDo changes to dir, runs fn, restores original dir.
func chdirDo[T any](t *testing.T, dir string, fn func() T) T {
	t.Helper()
	cwd, err := os.Getwd()
	if err != nil {
		t.Fatalf("Getwd: %v", err)
	}
	if err := os.Chdir(dir); err != nil {
		t.Fatalf("Chdir %s: %v", dir, err)
	}
	defer func() {
		if err := os.Chdir(cwd); err != nil {
			t.Errorf("restore Chdir %s: %v", cwd, err)
		}
	}()
	return fn()
}

func projectName(t *testing.T, tmpDir string) string {
	t.Helper()
	return filepath.Base(tmpDir)
}

func initGitRepo(t *testing.T, dir string) {
	t.Helper()
	git(t, dir, "init", "--initial-branch=main")
	git(t, dir, "config", "user.email", "test@test.com")
	git(t, dir, "config", "user.name", "Test")
	mustWriteFile(t, filepath.Join(dir, "README.md"), "# test\n")
	git(t, dir, "add", "README.md")
	git(t, dir, "commit", "-m", "initial")
}

func git(t *testing.T, dir string, args ...string) {
	t.Helper()
	cmd := exec.Command("git", args...)
	cmd.Dir = dir
	out, err := cmd.CombinedOutput()
	if err != nil {
		t.Fatalf("git %v: %v\n%s", args, err, out)
	}
}

func mustWriteFile(t *testing.T, path, content string) {
	t.Helper()
	if err := os.WriteFile(path, []byte(content), 0644); err != nil {
		t.Fatalf("write %s: %v", path, err)
	}
}

func openTestDB(t *testing.T, path string) *db.DB {
	t.Helper()
	database, err := db.Open(path)
	if err != nil {
		t.Fatalf("open DB %s: %v", path, err)
	}
	return database
}

func forgeDBPath(home string) string {
	return filepath.Join(home, ".forge", "forge.db")
}

func insertPrinciple(t *testing.T, database *db.DB, projectID, title string, impact float64, files []string) {
	t.Helper()
	_, err := database.InsertPrinciple(&db.Principle{
		ID:           fmt.Sprintf("%s-%s", projectID, title),
		TS:           time.Now().UTC().Format(time.RFC3339),
		Type:         "pattern",
		Title:        title,
		Narrative:    "Test narrative for: " + title,
		ImpactScore:  impact,
		ProjectID:    projectID,
		FilesModified: files,
	})
	if err != nil {
		t.Fatalf("insert principle %q: %v", title, err)
	}
}
