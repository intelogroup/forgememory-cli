func TestIntersectStrings(t *testing.T) {
	cases := []struct {
		name string
		a, b []string
		want []string
	}{
		{"empty a", nil, []string{"a"}, nil},
		{"empty b", []string{"a"}, nil, nil},
		{"exact match", []string{"a.go", "b.go"}, []string{"a.go", "b.go"}, []string{"a.go", "b.go"}},
		{"partial match", []string{"a.go"}, []string{"a.go", "b.go"}, []string{"a.go"}},
		{"no overlap", []string{"a.go"}, []string{"b.go"}, nil},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			got := intersectStrings(tc.a, tc.b)
			if len(got) != len(tc.want) {
				t.Fatalf("intersectStrings(%v,%v) = %v, want %v", tc.a, tc.b, got, tc.want)
			}
			for i := range got {
				if got[i] != tc.want[i] {
					t.Errorf("intersectStrings(%v,%v) = %v, want %v", tc.a, tc.b, got, tc.want)
				}
			}
		})
	}
}

